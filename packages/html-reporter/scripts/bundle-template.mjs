/**
 * Bundle Template Script
 *
 * Reads the development template (template/index.html) and replaces CDN
 * script imports with inlined library code from node_modules.
 *
 * Output: src/template.ts — exports the complete HTML as a string constant.
 *
 * This runs at compile time (before tsc) so that the bundled template
 * is available as a TypeScript module in the compiled output.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(__dirname, '..');

// For now, just read the template as-is.
// TODO: Replace CDN imports with inlined library code from node_modules
const templatePath = resolve(packageRoot, 'template', 'index.html');
const templateContent = readFileSync(templatePath, 'utf8');

// Escape backticks and ${} for template literal embedding
const escaped = templateContent
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');

const output = `// Auto-generated by scripts/bundle-template.mjs — do not edit manually
export const reportTemplate = \`${escaped}\`;
`;

const outputPath = resolve(packageRoot, 'src', 'template.ts');
writeFileSync(outputPath, output, 'utf8');

console.log(`Bundled template written to src/template.ts (${Math.round(output.length / 1024)}KB)`);
